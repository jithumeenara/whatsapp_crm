export const FORM_STRINGS: Record<FormLang, FormStrings> = { en, ml, hi, ta, kn, te, ar }

/** The plain words a business may reword (the ones with numbers or
 *  names in them stay as they are). */
export const UI_TEXT_KEYS = (Object.keys(en) as (keyof FormStrings)[]).filter(
  (k): k is { [K in keyof FormStrings]: FormStrings[K] extends string ? K : never }[keyof FormStrings] => typeof en[k] === "string",
)

/** The form's words in `lang`, with the business's own rewording (ui:<word>). */
export function formStrings(lang: FormLang, copy?: Record<string, string>): FormStrings {
  const base = FORM_STRINGS[lang] ?? en
  if (!copy) return base
  const out = { ...base } as Record<string, unknown>
  for (const k of UI_TEXT_KEYS) {
    const v = copy[`ui:${k}`]
    if (v) out[k] = v
  }
  return out as FormStrings
}
